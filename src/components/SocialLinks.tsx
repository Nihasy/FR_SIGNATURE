export function whatsappHref(number: string) {
  return `https://wa.me/${number.replace(/[^\d]/g, "")}`;
}

export function SocialLinks({ settings, className = "" }: { settings: Settings; className?: string }) {
  const links = [
    settings.instagram_url && { key: "instagram", href: settings.instagram_url, label: "Instagram" },
    settings.facebook_url && { key: "facebook", href: settings.facebook_url, label: "Facebook" },
    settings.linkedin_url && { key: "linkedin", href: settings.linkedin_url, label: "LinkedIn" },
    settings.whatsapp && { key: "whatsapp", href: whatsappHref(settings.whatsapp), label: "WhatsApp" },
  ].filter(Boolean) as { key: keyof typeof icons; href: string; label: string }[];
  if (!links.length) return null;
  return (
    <ul className={`flex gap-3 ${className}`}>
      {links.map((l) => (
        <li key={l.key}>
          <a
            href={l.href}
            target="_blank"
            rel="noopener noreferrer"
            aria-label={l.label}
            className="flex h-10 w-10 items-center justify-center border border-line text-paper/70 transition-colors hover:border-red hover:bg-red hover:text-white"
          >
            <svg viewBox="0 0 24 24" width="16" height="16" fill="currentColor" aria-hidden="true">
              <path d={icons[l.key]} />
            </svg>
          </a>
        </li>
      ))}
    </ul>
  );
}
